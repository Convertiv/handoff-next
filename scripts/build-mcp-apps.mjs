// Bundles the MCP App client(s) (Track 6.2) into self-contained JS and emits it
// as a base64 string module the MCP server inlines into the ui:// resource HTML.
// Base64 avoids template-literal escaping issues in the generated .ts.
//
// Run in the build pipeline (before `next build`) and committed so typecheck
// has the artifact. Regenerate after editing any *.client.ts.
import esbuild from 'esbuild';
import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();

const APPS = [
  {
    entry: 'src/app/lib/mcp/apps/component-preview.client.ts',
    out: 'src/app/lib/mcp/apps/component-preview.bundle.ts',
    exportName: 'COMPONENT_PREVIEW_APP_JS_B64',
  },
  {
    entry: 'src/app/lib/mcp/apps/token-palette.client.ts',
    out: 'src/app/lib/mcp/apps/token-palette.bundle.ts',
    exportName: 'TOKEN_PALETTE_APP_JS_B64',
  },
];

for (const app of APPS) {
  const result = await esbuild.build({
    entryPoints: [path.join(root, app.entry)],
    bundle: true,
    write: false,
    format: 'esm',
    platform: 'browser',
    target: 'es2022',
    minify: true,
    sourcemap: false,
  });
  const js = result.outputFiles[0].text;
  const b64 = Buffer.from(js, 'utf8').toString('base64');
  const banner = '// GENERATED by scripts/build-mcp-apps.mjs — do not edit by hand.\n';
  fs.writeFileSync(
    path.join(root, app.out),
    `${banner}export const ${app.exportName} = ${JSON.stringify(b64)};\n`
  );
  console.log(`[mcp-apps] ${app.entry} → ${app.out} (${(js.length / 1024).toFixed(1)} KB)`);
}
